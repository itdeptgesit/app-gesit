-- Employee transfer audit trail. Employee identity stays in user_accounts.
CREATE TABLE IF NOT EXISTS public.employee_transfer_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL,
  employee_code TEXT,
  effective_date DATE NOT NULL,
  old_company TEXT,
  old_branch TEXT,
  old_department TEXT,
  old_job_title TEXT,
  old_job_level TEXT,
  new_company TEXT,
  new_branch TEXT,
  new_department TEXT,
  new_job_title TEXT,
  new_job_level TEXT,
  reason TEXT,
  transferred_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_employee_transfer_history_employee ON public.employee_transfer_history(employee_id, effective_date DESC);
ALTER TABLE public.employee_transfer_history ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS employee_transfer_history_hr_access ON public.employee_transfer_history;
CREATE POLICY employee_transfer_history_hr_access ON public.employee_transfer_history FOR ALL TO authenticated
USING (EXISTS (SELECT 1 FROM public.user_accounts u WHERE lower(u.email)=lower(auth.jwt()->>'email') AND (lower(u.role) IN ('admin','super admin') OR 'employee-data'=ANY(COALESCE(u.groups, '{}'::text[])))))
WITH CHECK (EXISTS (SELECT 1 FROM public.user_accounts u WHERE lower(u.email)=lower(auth.jwt()->>'email') AND (lower(u.role) IN ('admin','super admin') OR 'employee-data'=ANY(COALESCE(u.groups, '{}'::text[])))));
